#if DEBUG
import Foundation

/// Network-free Song details for fixture launches: the seeded "Tum Hi Ho" gets a canned art-track description,
/// every other fixture song has no details so the unavailable state can be exercised.
struct DebugTrackDetailsFixture: TrackDetailsFetching {
    static let detailedTrackID = "fsiPzT50ZiM"
    static let fetchedAt = Date(timeIntervalSince1970: 1_789_819_200)

    static let description = """
    Provided to YouTube by Super Cassettes Industries Private Limited

    Tum Hi Ho · Arijit Singh

    Aashiqui 2

    ℗ 2013 T-Series

    Released on: 2013-04-01

    Composer: Mithoon
    Lyricist: Mithoon
    Producer: Mithoon

    Auto-generated by YouTube.
    """

    @MainActor static func store(connectivity: ConnectivityMonitor) -> TrackDetailsStore {
        TrackDetailsStore(directory: nil, fetcher: DebugTrackDetailsFixture(), isOffline: { connectivity.isOffline })
    }

    func fetch(_ track: Track, refresh: Bool) async -> TrackDetails? {
        try? await Task.sleep(for: .milliseconds(150))
        guard track.id == Self.detailedTrackID, let parsed = ProvidedToYouTubeDescriptionParser.parse(Self.description) else { return nil }
        var details = TrackDetails(track: track, fetchedAt: Self.fetchedAt)
        details.credits = parsed.credits
        details.albumTitle = parsed.album
        details.releaseDate = parsed.releaseDate
        details.releaseDateText = parsed.releasedOn
        details.phonogramLine = parsed.phonogramLine
        details.channelTitle = "Arijit Singh - Topic"
        details.publishedAt = Date(timeIntervalSince1970: 1_437_000_000)
        details.viewCount = 1_234_567_890
        details.description = Self.description
        details.sources = [.youTubeDataAPI, .youTubeDescription]
        return details
    }
}
#endif
