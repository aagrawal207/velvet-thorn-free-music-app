@MainActor
final class SongDetailsStoreTests: XCTestCase {
    private func makeDirectory() throws -> URL {
        let url = FileManager.default.temporaryDirectory.appendingPathComponent("SongDetailsStoreTests-\(UUID().uuidString)", isDirectory: true)
        try FileManager.default.createDirectory(at: url, withIntermediateDirectories: true)
        addTeardownBlock { try? FileManager.default.removeItem(at: url) }
        return url
    }

    private func details(for track: Track) -> TrackDetails {
        var details = TrackDetails(track: track, fetchedAt: Date(timeIntervalSince1970: 1_700_000_000))
        details.credits = [.init(role: .composer, names: ["Mithoon"])]
        details.viewCount = 42
        return details
    }

    func testMemoryHitAndDiskHitAcrossStoreInstancesAvoidRefetching() async throws {
        let directory = try makeDirectory()
        let track = SongDetailsFixtures.track
        let fetcher = SongDetailsRecordingFetcher(results: [track.id: details(for: track)])
        let store = TrackDetailsStore(directory: directory, fetcher: fetcher)
        let first = await store.details(for: track, refresh: false)
        XCTAssertEqual(first?.viewCount, 42)
        _ = await store.details(for: track, refresh: false)
        XCTAssertEqual(fetcher.callCount, 1, "The second lookup is a memory hit")
        let file = TrackDetailsStore.fileURL(for: track.id, in: directory)
        XCTAssertTrue(FileManager.default.fileExists(atPath: file.path))

        let second = TrackDetailsStore(directory: directory, fetcher: fetcher)
        let fromDisk = await second.details(for: track, refresh: false)
        XCTAssertEqual(fromDisk, first)
        XCTAssertEqual(fetcher.callCount, 1, "A new store instance reads the JSON file instead of fetching")
        let memoryCount = await second.memoryCount
        XCTAssertEqual(memoryCount, 1)

        var refreshed = details(for: track)
        refreshed.viewCount = 43
        fetcher.set(refreshed, for: track.id)
        let updated = await second.details(for: track, refresh: true)
        XCTAssertEqual(updated?.viewCount, 43)
        XCTAssertEqual(fetcher.callCount, 2)
        XCTAssertEqual(fetcher.calls.last?.refresh, true)
    }

    func testRefreshFailureKeepsTheFactsAlreadyShown() async throws {
        let track = SongDetailsFixtures.track
        let fetcher = SongDetailsRecordingFetcher(results: [track.id: details(for: track)])
        let store = TrackDetailsStore(directory: nil, fetcher: fetcher)
        let first = await store.details(for: track, refresh: false)
        fetcher.set(nil, for: track.id)
        let afterFailedRefresh = await store.details(for: track, refresh: true)
        XCTAssertEqual(afterFailedRefresh, first)
        XCTAssertEqual(fetcher.callCount, 2)
    }

    func testDiskFilesAreBoundedWithOldestRemovedFirst() async throws {
        XCTAssertEqual(TrackDetailsStore.Configuration().diskCapacity, 500)
        XCTAssertEqual(TrackDetailsStore.Configuration().memoryCapacity, 64)
        let directory = try makeDirectory()
        var configuration = TrackDetailsStore.Configuration()
        configuration.diskCapacity = 5
        configuration.memoryCapacity = 2
        let tracks = (0..<8).map { Track(id: "video\($0)ABCDEF", title: "Song \($0)", artists: ["Artist"], duration: 200, isAudioRecording: true) }
        let fetcher = SongDetailsRecordingFetcher(results: Dictionary(uniqueKeysWithValues: tracks.map { ($0.id, details(for: $0)) }))
        let store = TrackDetailsStore(directory: directory, fetcher: fetcher, configuration: configuration)
        for track in tracks {
            _ = await store.details(for: track, refresh: false)
            // Modification dates need to differ for oldest-first eviction to be observable.
            try await Task.sleep(for: .milliseconds(30))
        }
        let files = try FileManager.default.contentsOfDirectory(atPath: directory.path).filter { $0.hasSuffix(".json") }.sorted()
        XCTAssertEqual(files.count, 5)
        XCTAssertEqual(files, (3..<8).map { "video\($0)ABCDEF.json" })
        let memoryCount = await store.memoryCount
        XCTAssertEqual(memoryCount, 2)
    }

    func testMissingDetailsAreRememberedForFifteenMinutesInMemoryOnly() async throws {
        let directory = try makeDirectory()
        let clock = CatalogTestClock()
        let track = SongDetailsFixtures.track
        let fetcher = SongDetailsRecordingFetcher(results: [:])
        let store = TrackDetailsStore(directory: directory, fetcher: fetcher, now: { clock.now })
        let first = await store.details(for: track, refresh: false)
        XCTAssertNil(first)
        _ = await store.details(for: track, refresh: false)
        XCTAssertEqual(fetcher.callCount, 1, "A missing result is cached")
        XCTAssertTrue(try FileManager.default.contentsOfDirectory(atPath: directory.path).isEmpty, "Missing results never reach the disk")
