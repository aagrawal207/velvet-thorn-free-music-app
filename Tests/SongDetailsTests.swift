    func testDetailsRoundTripThroughJSONWithRolesAndDates() throws {
        var details = TrackDetails(track: SongDetailsFixtures.track, fetchedAt: Date(timeIntervalSince1970: 1_700_000_000))
        details.credits = [.init(role: .composer, names: ["Mithoon"]), .init(role: .other("Film Director"), names: ["Mohit Suri"])]
        details.releaseDate = Date(timeIntervalSince1970: 1_364_774_400)
        details.viewCount = 1_234_567_890
        details.sources = [.youTubeDescription, .musicBrainz]
        let encoder = JSONEncoder()
        encoder.dateEncodingStrategy = .iso8601
        let decoder = JSONDecoder()
        decoder.dateDecodingStrategy = .iso8601
        let decoded = try decoder.decode(TrackDetails.self, from: encoder.encode(details))
        XCTAssertEqual(decoded, details)
    }

    func testDescriptionsAreTrimmedNormalisedAndBounded() {
        XCTAssertNil(TrackDetails.trimmedDescription(nil))
        XCTAssertNil(TrackDetails.trimmedDescription("  \n "))
        XCTAssertEqual(TrackDetails.trimmedDescription("a\r\nb "), "a\nb")
        let long = String(repeating: "\u{0915}", count: 10_000)
        let clipped = TrackDetails.trimmedDescription(long)
        XCTAssertLessThanOrEqual(clipped?.utf8.count ?? .max, TrackDetails.maximumDescriptionBytes)
        XCTAssertTrue(clipped?.allSatisfy { $0 == "\u{0915}" } ?? false, "Clipping must not split a multibyte scalar")
        XCTAssertEqual(TrackDetails.date(from: "2013-04-01"), ISO8601DateFormatter().date(from: "2013-04-01T00:00:00Z"))
