final class SongDetailsRecordingFetcher: TrackDetailsFetching, @unchecked Sendable {
    private let lock = NSLock()
    private var results: [String: TrackDetails?]
    private(set) var calls: [(id: String, refresh: Bool)] = []

    init(results: [String: TrackDetails?]) { self.results = results }

    func set(_ details: TrackDetails?, for id: String) { lock.withLock { results[id] = details } }
    var callCount: Int { lock.withLock { calls.count } }

    func fetch(_ track: Track, refresh: Bool) async -> TrackDetails? {
        lock.withLock {
            calls.append((track.id, refresh))
            return results[track.id] ?? nil
        }
    }
}

